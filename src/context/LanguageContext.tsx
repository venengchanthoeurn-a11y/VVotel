const LanguageContext = createContext<LanguageContextType>({
  lang: "km",
  setLang: () => {},
  t: () => "",
  isRtl: false,
  currentLanguageMeta: SUPPORTED_LANGUAGES[0],
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({
  children,
}) => {
  const [lang, setLangState] = useState<Language>("km");

  useEffect(() => {
    const saved = localStorage.getItem("vvotel_lang") as Language;
    const validCodes = SUPPORTED_LANGUAGES.map((l) => l.code);
    if (saved && validCodes.includes(saved)) {
      setLangState(saved);
      document.documentElement.lang = saved;
      document.documentElement.dir = saved === "ar" ? "rtl" : "ltr";
    }
  }, []);

  const setLang = (newLang: Language) => {
    setLangState(newLang);
    localStorage.setItem("vvotel_lang", newLang);
    if (typeof document !== "undefined") {
      document.documentElement.lang = newLang;
      document.documentElement.dir = newLang === "ar" ? "rtl" : "ltr";
    }
  };

  const t = (key: string): string => {
    if (translations[key]) {
      const entry = translations[key];
      return entry[lang] || entry["en"] || entry["km"] || key;
    }
    return key;
  };

  const isRtl = lang === "ar";
  const currentLanguageMeta =
    SUPPORTED_LANGUAGES.find((l) => l.code === lang) || SUPPORTED_LANGUAGES[0];

  return (
    <LanguageContext.Provider
      value={{ lang, setLang, t, isRtl, currentLanguageMeta }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
